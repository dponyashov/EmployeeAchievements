create table t_component (id bigint generated by default as identity, name varchar(255), primary key (id));
create table t_department (id bigint generated by default as identity, name varchar(255), primary key (id));
create table t_positions (id bigint generated by default as identity, name varchar(255), primary key (id));
create table t_profiles (department_id bigint, id bigint generated by default as identity, position_id bigint, user_id bigint unique, email varchar(255), first_name varchar(255), last_name varchar(255), primary key (id));
create table t_roles (id bigint generated by default as identity, description varchar(255), name varchar(255), primary key (id));
create table t_services (id bigint generated by default as identity, name varchar(255), primary key (id));
create table t_task_query (id bigint generated by default as identity, task_id bigint, name varchar(255), primary key (id));
create table t_tasks (enter_date date, enter_time time(0), author_id bigint, component_id bigint, id bigint generated by default as identity, month bigint, profile_id bigint, service_id bigint, year bigint, description varchar(1000), title varchar(255), primary key (id));
create table t_user_roles (id bigint generated by default as identity, role_id bigint not null, user_id bigint not null);
create table t_users (id bigint generated by default as identity, password varchar(255), user_name varchar(255), primary key (id));


alter table if exists t_profiles add constraint FK_department foreign key (department_id) references t_department;
alter table if exists t_profiles add constraint FK_positions foreign key (position_id) references t_positions;
alter table if exists t_profiles add constraint FK_users foreign key (user_id) references t_users;
alter table if exists t_task_query add constraint FK_tasks foreign key (task_id) references t_tasks;
alter table if exists t_tasks add constraint FK_author foreign key (author_id) references t_profiles;
alter table if exists t_tasks add constraint FK_component foreign key (component_id) references t_component;
alter table if exists t_tasks add constraint FK_profiles foreign key (profile_id) references t_profiles;
alter table if exists t_tasks add constraint FK_services foreign key (service_id) references t_services;
alter table if exists t_user_roles add constraint FK_roles foreign key (role_id) references t_roles;
alter table if exists t_user_roles add constraint FK_users foreign key (user_id) references t_users;


